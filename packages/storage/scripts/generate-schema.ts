import { writeFileSync } from "node:fs"
import { DB_SCHEMA_VERSION, DimahS3DB } from "@dimah-s3/db"
import { drizzleAdapter } from "@dimah-s3/db/adapters/drizzle"

const output = new URL(
  "../../db/src/schema/dimah-s3.schema.ts",
  import.meta.url
)

// Generating needs the dialect, not a connection.
const { code } = DimahS3DB.client(
  drizzleAdapter({ db: undefined, provider: "postgresql" })
).generateSchema("latest")

/** Replaces `search` once, or fails when the generator's output moved. */
function rewrite(source: string, search: RegExp, replacement: string) {
  if (!search.test(source)) {
    throw new Error(`[storage] generated schema has no ${search}`)
  }
  return source.replace(search, replacement)
}

// The tables live in the `storage` PostgreSQL schema, and `@repo/db`
// registers them on its own relations next to the auth tables.
let schema = rewrite(code, /\bpgTable\b/, "pgSchema")
schema = rewrite(
  schema,
  /^import \{ defineRelations \} from "drizzle-orm"\n/m,
  ""
)
schema = rewrite(schema, /^export const relations = .*\n?/m, "")
schema = schema.replaceAll(/\bpgTable\(/g, "storagePg.table(")
schema = rewrite(
  schema,
  /^(import .*\n)+/m,
  '$&\n/** PostgreSQL schema for dimah-s3 tables (not `public`). */\nexport const storagePg = pgSchema("storage")\n'
)

writeFileSync(
  output,
  `/**
 * Generated by \`pnpm --filter @repo/db storage:generate\` from \`@dimah-s3/db\`
 * (schema ${DB_SCHEMA_VERSION}). Do not edit: run it again after upgrading dimah-s3.
 *
 * @see https://s3.dimah.dev/docs/db/setup
 */
${schema}`
)
